def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--apply', action='store_true', help='真正写盘（默认只预演）')
    args = ap.parse_args()

    print('=== 本次定版口径 ===')
    print(f'  主表 {N_TOTAL} 家 | 应参评 {N_APPLIC} | 不适用 {N_NONAPPLIC} | '
          f'一级 {LV1} / 二级 {LV2} / 三级 {LV3} / 未定级 {LV0} | 等级非空 {N_LEVEL_OK} | '
          f'电话 {N_PHONE} | 等次 {N_LEVELSUB}')

    files = {}
    already = 0
    for path, old, new, cnt in PAIRS:
        text = files.get(path)
        if text is None:
            text = open(path, encoding='utf-8').read()
        got = text.count(old)
        if got == 0 and new in text:
            # 已同步过：字面量替换天然不可重入，这里把"新值已在"当作成功，
            # 让脚本可以反复跑（改完数据再跑一次即可，不需要人工判断哪几处已改）。
            already += 1
            files[path] = text
            continue
        if got != cnt:
            print(f'\n✗ 匹配失败：{path}')
            print(f'  期望 {cnt} 次，实际 {got} 次')
            print(f'  片段：{old[:90]}...')
            sys.exit(1)
        files[path] = text.replace(old, new)
        files[path + '\0consumed'] = True
    print(f'\n（其中 {already} 处此前已同步，跳过）')

    for path, anchor, where, block, marker in INSERTS:
        text = files.get(path)
        if text is None:
            text = open(path, encoding='utf-8').read()
        if anchor not in text:
            print(f'\n✗ 插入锚点未找到：{path} :: {anchor[:60]}')
            sys.exit(1)
        if marker in text:
            print(f'  · 已存在，跳过插入：{path} :: {marker[:34]}')
            files[path] = text
            continue
        if where == 'BEFORE':
            text = text.replace(anchor, block + anchor, 1)
        else:
            text = text.replace(anchor, anchor + block, 1)
        files[path] = text

    n_touch = len({p for p, *_ in PAIRS} | {p for p, *_ in INSERTS} | {p for p, *_ in APPENDS})
    print(f'\n=== 待改动 {n_touch} 个文件 ===')
    for p in sorted({x[0] for x in PAIRS} | {x[0] for x in INSERTS} | {x[0] for x in APPENDS}):
        n = (sum(1 for x in PAIRS if x[0] == p) + sum(1 for x in INSERTS if x[0] == p)
             + sum(1 for x in APPENDS if x[0] == p))
        print(f'  {p}  （{n} 处）')

    for path, block, marker in APPENDS:
        text = files.get(path)
        if text is None:
            text = open(path, encoding='utf-8').read()
        if marker in text:
            print(f'  · 已存在，跳过追加：{path} :: {marker[:34]}')
            continue
        files[path] = text.rstrip('\n') + '\n' + block
        print(f'  · 追加章节：{path} :: {marker[:34]}')

    if not args.apply:
        print('\n（预演模式，未写盘。加 --apply 落盘）')
        return

    for path, text in files.items():
        if path.endswith('\0consumed'):
            continue
        open(path, 'w', encoding='utf-8').write(text)
        print(f'  ✓ 已写 {path}')

    print('\n=== 残留旧值扫描 ===')
    bad = 0
    for path in SCAN_FILES:
        if not os.path.exists(path):
            continue
        text = open(path, encoding='utf-8').read()
        for needle, why in STALE:
            if needle in text:
                for ln, line in enumerate(text.split('\n'), 1):
                    if needle in line:
                        print(f'  ⚠️ {path}:{ln} {why} → {line.strip()[:100]}')
                        bad += 1
    print('  ✓ 无残留' if not bad else f'  共 {bad} 处待处理（若属历史叙述可保留，需人工确认）')


if __name__ == '__main__':
    main()
