def main():
    bad = [(kw, d) for kw, d, _, _ in ROWS if d not in VALID_DEPTS]
    if bad:
        print("❌ 以下 dept_name 不在真实科室词表内，请修正：")
        for kw, d in bad:
            print("   ", kw, "->", d)
        sys.exit(1)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    # 去重（同 keyword+dept 只保留一条）
    seen = set()
    cleaned = []
    for kw, dept, emg, note in ROWS:
        key = (kw, dept)
        if key in seen:
            continue
        seen.add(key)
        # 明确疾病（不含「科/症/不适/问题」等泛词）权重 1.0，否则 0.9
        weight = 1.0 if (len(kw) >= 2 and not any(x in kw for x in ("科", "不适", "问题", "疾病", "相关", "下降", "异常", "紊乱"))) else 0.9
        cleaned.append((kw, dept, CATEGORY.get(dept, "其他"), weight, emg, note))

    with open(OUT, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["keyword", "dept_name", "dept_category", "weight", "is_emergency", "note"])
        w.writerows(cleaned)

    depts = {}
    for r in cleaned:
        depts[r[1]] = depts.get(r[1], 0) + 1
    print(f"✅ 已生成 {len(cleaned)} 条映射 -> {OUT}")
    print(f"   覆盖 {len(depts)} 个科室；急诊条目 {sum(1 for r in cleaned if r[4]==1)} 条")
    for d, n in sorted(depts.items(), key=lambda x: -x[1]):
        print(f"     {n:3d}  {d}")


if __name__ == "__main__":
    main()
