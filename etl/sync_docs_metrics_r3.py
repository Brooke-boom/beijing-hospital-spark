# 落盘后仍出现的、需要人工判断的旧值（历史叙述允许保留，故只报告不自动改）。
# ⚠️ 清单要**带上下文**，否则会假阳性：例如 '223 家' 同时是 level_sub 的**正确新值**
#    （2.3%（223 家））和过时的三级家数，只写 '223 家' 会把改对的行也报出来。
RESIDUE_WATCH = ['9,789', '9789', '967 家应参评', '应参评 967', '一级 505', '505 家',
                 '三级 223', '二级 214', '8,822', '3,139 家', '9,334', '9,065',
                 '942 / 967', '255 家', '8,762', '89.5%', '1.5%（150', '9,787']


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--apply', action='store_true')
    args = ap.parse_args()

    files = {}
    for p in LIVE:
        if os.path.exists(p):
            files[p] = io.open(p, encoding='utf-8').read()
        else:
            print(f'  ！缺失：{p}')

    stat = {}
    for path, old, new in PAIRS:
        if old == new:
            continue
        targets = LIVE if path == '*' else [path]
        for p in targets:
            if p not in files or old not in files[p]:
                continue
            n = files[p].count(old)
            files[p] = files[p].replace(old, new)
            stat.setdefault(p, []).append(f'{old[:38]} → {new[:38]} ×{n}')

    total = sum(len(v) for v in stat.values())
    print(f'\n=== 命中 {len(stat)} 个文件 / {total} 类替换 ===')
    for p in sorted(stat):
        print(f'\n{p}')
        for line in stat[p]:
            print(f'    {line}')

    if args.apply:
        for p in stat:
            io.open(p, 'w', encoding='utf-8').write(files[p])
        print(f'\n[落盘] 已更新 {len(stat)} 个文件。')
    else:
        print('\n[预演] 未写入。加 --apply 落盘。')

    # 残差报告：仍有旧值出现的行（需人判是否为历史叙述）
    print('\n=== 落盘后残差（请人工判断是否属历史叙述）===')
    for p in LIVE:
        text = files.get(p)
        if text is None:
            continue
        t = text if args.apply else files[p]
        lines = t.splitlines()
        hits = [(i, l.strip()[:110]) for i, l in enumerate(lines, 1)
                if any(s in l for s in RESIDUE_WATCH)]
        if hits:
            print(f'\n{p}')
            for i, l in hits:
                print(f'  {i}| {l}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
