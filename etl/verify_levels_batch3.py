# 军队/部队医院一般均为三甲
MIL = ['解放军','人民解放军','武警','军队','部队','战略支援','火箭军','空军','海军','陆军']

def supported(name):
    for a in AUTH:
        if a in name:
            return a
    for m in MIL:
        if m in name:
            return '军队<' + m + '>'
    return None

matched = []
unmatched = []
for r in t3:
    s = supported(r['name'])
    if s:
        matched.append((r['id'], r['name'], s, r['category']))
    else:
        unmatched.append((r['id'], r['name'], r['district'], r['category']))

