# 噪声特征词：段落里含这些词说明它不是科室名（多为采编口径说明）
NOISE_TOKENS = ("口径", "未公开", "简介", "名单", "平台", "体系", "中心建设")


def norm_dept(seg):
    """把一段切分结果归一为标准科室名。

    返回 (标准科室名, 是否临床科室)；无法识别时返回 (None, False)。
    """
    if not seg:
        return None, False
    s = seg.strip()
    if not s or len(s) < 2:
        return None, False
    if s in DROP_SEGMENTS:
        return None, False
    if any(t in s for t in NOISE_TOKENS):
        return None, False
    if s in DEPT_ALIAS:
        s = DEPT_ALIAS[s]
    if s in DEPT_CATEGORY:
        return s, DEPT_CATEGORY[s] != "医技"
    return None, False


def is_clinical(dept):
    """该标准科室是否为临床科室（就医决策只推荐临床科室）。"""
    return DEPT_CATEGORY.get(dept, "医技") != "医技"
